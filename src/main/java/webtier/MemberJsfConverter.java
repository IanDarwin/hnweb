package webtier;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.faces.application.FacesMessage;
import jakarta.faces.component.UIComponent;
import jakarta.faces.context.FacesContext;
import jakarta.faces.convert.Converter;
import jakarta.faces.convert.ConverterException;
import jakarta.inject.Inject;
import jakarta.inject.Named;

import data.MemberList;

/**
 * This is used by the p:autoComplete in Renew.xhtml; esp. the line
 * var="_member" itemLabel="#{_member.names}" itemValue="#{_member.id}"
 * The itemLabel controls the argument to getAsObject;
 * the itemValue controls the argument to getAsString.
 * @author Ian Darwin
 */
@Named("memberConverter")
@ApplicationScoped
public class MemberJsfConverter implements Converter {

	@Inject()
	MemberList memberList;
	
	/** Input is of the form "Smith, Robin", generated by Member::getNames() */
	public Object getAsObject(FacesContext fc, UIComponent uic, String value) {
		if (value == null || value.trim().length() == 0) {
			return null;
		} else {
			try {
				String[] names = value.split(", ");
				// The last shall be first and the first shall be last
				return memberList.findByFirstNameAndLastName(names[1], names[0]);
			} catch (Exception e) {
				System.out.println("Conversion error: " + e);
				throw new ConverterException(new FacesMessage(FacesMessage.SEVERITY_ERROR, "Conversion Error", "Not a valid Member."));
			}
		}
	}

	/** Input is the primary key, as set by the p:autocomplete cited above. */
	public String getAsString(FacesContext fc, UIComponent uic, Object object) {
		if (object == null) {
			return null;
		} else {
			if (Long.class == object.getClass()) {
				return memberList.findById((Long)object).getNames();
			}
			if (Integer.class == object.getClass()) {
				long l = (Integer)object;
				return memberList.findById(l).getNames();
			}
			throw new IllegalArgumentException(
				String.format("getAsString expects long arg, not `%s' of type %s", object, object.getClass()));
		}
	}   
}     

